# Regenerates pixel/character.js from the vector character in character.html, so shape edits there carry over.
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'character.html').read_text()
lib = src[src.index('const INK'):src.index('// --- layout')]
(root / 'pixel' / 'character.js').write_text('// generated by build.py from character.html\n' + lib)
